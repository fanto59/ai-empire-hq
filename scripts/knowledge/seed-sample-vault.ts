/**
 * Regenerates the committed SAMPLE knowledge vault (knowledge/sample-vault)
 * through the real KnowledgeService, so the sample notes are exactly what
 * the service writes. Every note is marked origin "sample".
 *
 *   npm run knowledge:seed
 *
 * Safety: refuses to run against any directory other than the sample vault.
 */
import { promises as fs } from "node:fs";
import path from "node:path";
import { KnowledgeService } from "@/backend/knowledge/service";
import type { KnowledgeAccessContext } from "@/backend/knowledge/access";

// Targets: the committed sample vault (default) or, with --dev, the
// git-ignored development vault that the Research Agent writes reports into.
const dev = process.argv.includes("--dev");
const root = path.resolve(process.cwd(), dev ? ".data/knowledge-vault" : "knowledge/sample-vault");
if (!root.endsWith(path.join("knowledge", "sample-vault")) && !root.endsWith(path.join(".data", "knowledge-vault"))) {
  throw new Error("Refusing to seed outside the sample or development vault.");
}
if (dev) {
  const initialized = await fs
    .stat(path.join(root, "businesses", "sample-business", "business.md"))
    .then(() => true)
    .catch(() => false);
  if (initialized) {
    console.log("Development vault already has the sample notes; leaving it unchanged.");
    process.exit(0);
  }
}

const SEEDED_AT = new Date("2026-11-19T09:00:00.000Z");
const service = new KnowledgeService({ root, now: () => SEEDED_AT });
const seed: KnowledgeAccessContext = { principal: { kind: "system", id: "sample-seed" }, hq: true, businesses: "*", write: true };

const BIZ = "sample-business";
const SAMPLE_CALLOUT = `> [!warning] Sample content
> Demo note generated by \`npm run knowledge:seed\`. Illustrative only: not real research, not a real business.`;

// Start clean: only the generated scopes are removed (sample vault only; the
// development vault is seeded once, above, and never wiped).
if (!dev) for (const dir of ["hq", "businesses"]) await fs.rm(path.join(root, dir), { recursive: true, force: true });

await service.createNote(seed, {
  kind: "business",
  business: BIZ,
  title: "Sample Business (demo)",
  origin: "sample",
  status: "final",
  body: `${SAMPLE_CALLOUT}

# Sample Business (demo)

A placeholder business sector used to demonstrate how AI Empire HQ organizes knowledge. Each business gets its own folder with **projects**, **reports** and **agents**, and agents scoped to this business cannot read any other business's notes.

## Notes in this sector
- Project: [[businesses/sample-business/projects/sector-discovery|Sector discovery]]
- Agent: [[businesses/sample-business/agents/research-agent|Research Agent]]
- Report: [[businesses/sample-business/reports/2026/2026-11-19-sector-candidates-research|Sector candidates research]]
`,
});

await service.createNote(seed, {
  kind: "project",
  business: BIZ,
  title: "Sector discovery",
  origin: "sample",
  status: "draft",
  tasks: ["sample-task-sector-scan"],
  body: `${SAMPLE_CALLOUT}

# Sector discovery

**Goal:** decide which new business sectors are worth a closer look.

## Scope
1. Define evaluation criteria.
2. Shortlist candidate sector types.
3. Publish a research report and request owner approval before any spending.

## Linked task
- \`sample-task-sector-scan\` (sample task; task storage is not connected yet)
`,
});

await service.createNote(seed, {
  kind: "agent",
  business: BIZ,
  title: "Research Agent",
  slug: "research-agent",
  agent: "research-agent",
  origin: "sample",
  status: "final",
  body: `${SAMPLE_CALLOUT}

# Research Agent (prototype)

| Property | Value |
| --- | --- |
| Role | Research Agent |
| Business | Sample Business (demo) |
| Model | Not connected |
| Knowledge access | This business only (read and write) |

This profile describes a **planned** agent. No model, account or tool is connected.
`,
});

await service.createNote(seed, {
  kind: "report",
  business: BIZ,
  title: "Sector candidates research",
  slug: "sector-candidates-research",
  date: "2026-11-19",
  project: "sector-discovery",
  agent: "research-agent",
  tasks: ["sample-task-sector-scan"],
  origin: "sample",
  status: "final",
  tags: ["research"],
  body: `${SAMPLE_CALLOUT}

# Sector candidates research

**Project:** [[businesses/sample-business/projects/sector-discovery|Sector discovery]] · **Prepared for:** owner review · **Linked task:** \`sample-task-sector-scan\`

## Summary
This sample report shows the structure every research report in AI Empire HQ follows: a question, the criteria used, a shortlist, risks and a clear next step that needs human approval. The content below is a worked example of the format, not a recommendation.

## Question
Which kinds of online business are worth evaluating first, given a small budget and a preference for low operational risk?

## Evaluation criteria
| Criterion | What we look for |
| --- | --- |
| Startup cost | Can be tested without paid services |
| Operational load | Work an AI team can do with human review |
| Compliance risk | No regulated activity in the first phase |
| Time to first signal | Feedback within weeks, not months |

## Shortlist (illustrative)
1. **Digital templates and guides**: low cost to produce, easy to test, but crowded.
2. **Niche newsletter**: builds an owned audience; slow to grow.
3. **Research-as-a-service for small teams**: matches the research team's skills; needs careful scoping.

## Risks
- Every candidate needs real market validation before any money is spent.
- Anything involving customer data needs a privacy review first.

## Next step
> [!question] Owner decision needed
> Approve a lightweight validation plan for one candidate. No accounts, payments or public launches until approved.
`,
});

await service.createNote(seed, {
  kind: "business",
  business: "sample-business-b",
  title: "Sample Business B (demo)",
  origin: "sample",
  status: "final",
  body: `${SAMPLE_CALLOUT}

# Sample Business B (demo)

A second placeholder sector. It exists to demonstrate isolation: the Research Agent scoped to *Sample Business (demo)* cannot read this note.
`,
});

await service.createNote(seed, {
  kind: "project",
  business: null,
  title: "Knowledge service rollout",
  slug: "knowledge-service-rollout",
  origin: "sample",
  status: "draft",
  body: `${SAMPLE_CALLOUT}

# Knowledge service rollout (headquarters)

Headquarters notes live in \`hq/\` and are visible only to headquarters-level roles (the owner, the Chief AI Manager and the Central Project Manager).

## Milestones
- [x] Local Markdown vault with frontmatter
- [x] Business-scoped access control
- [ ] Authentication and per-agent access contexts
- [ ] Obsidian Headless Sync (requires owner approval; paid service)
`,
});

const { notes } = await service.listNotes(seed);
console.log(`Seeded ${notes.length} sample notes into ${path.relative(process.cwd(), root)}`);
for (const n of notes) console.log(`  ${n.path}`);
