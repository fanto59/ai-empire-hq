/**
 * Executive plan produced by the Chief AI Manager: validated again on our side
 * (never trust model output blindly) and rendered as a Markdown briefing.
 */
export interface ExecutivePlan {
  objective: string;
  summary: string;
  priorities: { rank: number; title: string; rationale: string; business: string | null }[];
  opportunities: string[];
  risks: { risk: string; severity: "low" | "medium" | "high"; mitigation: string }[];
  execution_plan: { step: number; owner: string; action: string; needs_owner_approval: boolean }[];
  decisions_for_owner: string[];
  recommendation: string;
}

export class PlanValidationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "PlanValidationError";
  }
}

const OWNERS = ["owner", "chief-ai-manager", "central-project-manager", "business-lead", "research-agent"];
/** Actions only people may take; a plan step mentioning them must need owner approval. */
const HUMAN_ONLY = /\b(approv\w*|spend\w*|budget\w*|pay\w*|purchas\w*|contract\w*|sign\w*|permission\w*|hire|fire|launch)\b/i;

const text = (v: unknown, field: string, max: number) => {
  if (typeof v !== "string" || !v.trim()) throw new PlanValidationError(`Plan field "${field}" must be non-empty text.`);
  return v.trim().slice(0, max);
};
const list = (v: unknown, field: string) => {
  if (!Array.isArray(v)) throw new PlanValidationError(`Plan field "${field}" must be a list.`);
  return v.slice(0, 20);
};

export function validatePlan(input: unknown): ExecutivePlan {
  if (typeof input !== "object" || input === null) throw new PlanValidationError("Plan must be an object.");
  const p = input as Record<string, unknown>;
  const steps = list(p.execution_plan, "execution_plan").map((s, i) => {
    const o = (s ?? {}) as Record<string, unknown>;
    const owner = OWNERS.includes(String(o.owner)) ? String(o.owner) : "owner";
    const action = text(o.action, `execution_plan[${i}].action`, 600);
    // Guardrail: anything that looks like spending, contracts, permissions or
    // approvals is flagged for the owner even if the model forgot to.
    const needs = o.needs_owner_approval === true || HUMAN_ONLY.test(action);
    return { step: Number.isInteger(o.step) ? (o.step as number) : i + 1, owner, action, needs_owner_approval: needs };
  });
  if (steps.length === 0) throw new PlanValidationError("Plan needs at least one execution step.");
  return {
    objective: text(p.objective, "objective", 1000),
    summary: text(p.summary, "summary", 2000),
    priorities: list(p.priorities, "priorities").map((x, i) => {
      const o = (x ?? {}) as Record<string, unknown>;
      return {
        rank: Number.isInteger(o.rank) ? (o.rank as number) : i + 1,
        title: text(o.title, `priorities[${i}].title`, 200),
        rationale: text(o.rationale, `priorities[${i}].rationale`, 800),
        business: typeof o.business === "string" && o.business.trim() ? o.business.trim().slice(0, 100) : null,
      };
    }),
    opportunities: list(p.opportunities, "opportunities").map((x, i) => text(x, `opportunities[${i}]`, 500)),
    risks: list(p.risks, "risks").map((x, i) => {
      const o = (x ?? {}) as Record<string, unknown>;
      const severity = o.severity === "high" || o.severity === "medium" ? o.severity : "low";
      return { risk: text(o.risk, `risks[${i}].risk`, 500), severity, mitigation: text(o.mitigation, `risks[${i}].mitigation`, 500) };
    }),
    execution_plan: steps,
    decisions_for_owner: list(p.decisions_for_owner, "decisions_for_owner").map((x, i) => text(x, `decisions_for_owner[${i}]`, 500)),
    recommendation: text(p.recommendation, "recommendation", 1000),
  };
}

export function renderBriefing(plan: ExecutivePlan, meta: { goal: string; model: string; taskId: string; costLabel: string; at: string; requestedWork: string[] }): string {
  const esc = (s: string) => s.replace(/\[\[/g, "[ [").replace(/<\/?[a-z][^>]*>/gi, "");
  const lines = [
    "# Executive briefing",
    "",
    "> [!info] AI-generated by the Chief AI Manager",
    `> ${meta.model} · cost ${meta.costLabel} · ${meta.at}. Recommendations only: spending, contracts, permissions and approvals remain the owner's decisions.`,
    "",
    `**Owner objective:** ${esc(meta.goal)}`,
    "",
    `**Linked task:** \`${meta.taskId}\``,
    "",
    "## Summary",
    esc(plan.summary),
    "",
    "## Recommendation",
    esc(plan.recommendation),
    "",
    "## Priorities",
    ...plan.priorities.map((p) => `${p.rank}. **${esc(p.title)}**${p.business ? ` (${esc(p.business)})` : ""}: ${esc(p.rationale)}`),
    "",
    "## Proposed execution plan",
    "| # | Owner | Action | Owner approval |",
    "| --- | --- | --- | --- |",
    ...plan.execution_plan.map((s) => `| ${s.step} | ${s.owner} | ${esc(s.action).replace(/\|/g, "/")} | ${s.needs_owner_approval ? "required" : "-"} |`),
    "",
    "## Opportunities",
    ...(plan.opportunities.length ? plan.opportunities.map((o) => `- ${esc(o)}`) : ["- None identified."]),
    "",
    "## Risks",
    ...(plan.risks.length ? plan.risks.map((r) => `- **${r.severity}** — ${esc(r.risk)} _Mitigation:_ ${esc(r.mitigation)}`) : ["- None identified."]),
    "",
    "## Decisions for the owner",
    ...(plan.decisions_for_owner.length ? plan.decisions_for_owner.map((d) => `- [ ] ${esc(d)}`) : ["- None."]),
    "",
    "## Work requested from the Project Manager",
    ...(meta.requestedWork.length ? meta.requestedWork.map((w) => `- ${esc(w)}`) : ["- None."]),
  ];
  return lines.join("\n");
}
